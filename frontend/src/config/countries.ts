export function findCountry(value: string): string | undefined {
  const needle = value.trim().toLowerCase();
  return COUNTRIES.find((country) => country.toLowerCase() === needle);
}

export function findNigerianState(value: string): string | undefined {
  const needle = value.trim().toLowerCase();
  return NIGERIAN_STATES.find((state) => state.toLowerCase() === needle);
}
